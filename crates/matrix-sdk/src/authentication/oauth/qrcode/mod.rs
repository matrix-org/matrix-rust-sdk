    /// The APIs that the servers support in [`mock_qr_code_login_server()`].
    struct SupportedApis {
        server_metadata: ServerMetadata,
        msc_4388: Msc4388,
        msc_4108: Msc4108,
    }

    impl SupportedApis {
        /// All the APIs are supported.
        fn all() -> Self {
            Self {
                server_metadata: ServerMetadata::WithDeviceAuthorizationGrant,
                msc_4388: Msc4388::Supported,
                msc_4108: Msc4108::Supported,
            }
        }
    }

    /// Mock the servers to support the given APIs for QR code login.
    async fn mock_qr_code_login_server(apis: SupportedApis) -> MatrixMockServer {
        let server = MatrixMockServer::new().await;

        let versions = server.mock_versions();
        let versions = match apis.msc_4108 {
            Msc4108::Supported => versions.with_feature("org.matrix.msc4108", true).ok(),
            Msc4108::NotSupported => versions.ok(),
            Msc4108::Error => versions.error500(),
        };
        versions.named("versions").mount().await;

        let oauth_server = server.oauth();
        let server_metadata = oauth_server.mock_server_metadata();
        let server_metadata = match apis.server_metadata {
            ServerMetadata::WithDeviceAuthorizationGrant => server_metadata.ok(),
            ServerMetadata::WithoutDeviceAuthorizationGrant => {
                server_metadata.ok_without_device_authorization()
            }
            ServerMetadata::NotSupported => server_metadata.error_unrecognized(),
            ServerMetadata::Error => server_metadata.error500(),
        };
        server_metadata.named("server_metadata").mount().await;

        let rendezvous_discovery = server.mock_rendezvous_discovery();
        let rendezvous_discovery = match apis.msc_4388 {
            Msc4388::Supported => rendezvous_discovery.ok(true),
            Msc4388::CreateUnavailable => rendezvous_discovery.ok(false),
            Msc4388::NotSupported => rendezvous_discovery.respond_with(ResponseTemplate::new(404)),
            Msc4388::Error => rendezvous_discovery.respond_with(ResponseTemplate::new(503)),
        };
        rendezvous_discovery.named("rendezvous_discovery").mount().await;

        server
    }

